// Post-processes the Better Auth generated schema (pnpm auth:generate):
// every timestamp becomes timestamptz, like the rest of the database (04-veri §4).
import { readFileSync, writeFileSync } from "node:fs";

const file = "src/server/db/schema/auth.ts";
const source = readFileSync(file, "utf8");
const fixed = source.replace(
  /timestamp\("([a-z_]+)"\)/g,
  'timestamp("$1", { withTimezone: true })',
);
writeFileSync(
  file,
  `// Generated by Better Auth CLI — do not edit by hand. Regenerate: pnpm auth:generate\n${fixed.replace(/^\/\/ Generated by Better Auth CLI.*\n/, "")}`,
);
console.log(`✓ ${file}: timestamps → timestamptz`);
